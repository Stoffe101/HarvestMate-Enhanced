-- Builds tests/fixtures/fgps_terrain.lua: what Forever-GPS's REAL walking grid
-- answers (ForeverGPS.API.LocalPath, API v2) for every leg of real HME loops.
-- HME's terrain tests replay these answers, so they test against the real
-- engine's output without needing Forever-GPS's client simulation.
--
-- Run from a Forever-GPS checkout (branch feature/public-api), after
-- `python -I tools/assemble.py`:
--   lua ../HarvestMate-Enhanced/tools/terrain_fixture.lua <routes.lua> <out.lua>
-- routes.lua holds lines `{ mapID = N, name = "...", points = { x1, y1, ... } },`
-- (HME's own planner output; see TESTING.md).
package.path = "tests/?.lua;" .. package.path
local Stack = require("support.stack")
local routesFile, outFile = arg[1], arg[2]
assert(routesFile and outFile, "usage: terrain_fixture.lua <routes.lua> <out.lua>")
local routes = assert(load("return {" .. io.open(routesFile):read("a") .. "}"))()
local c = Stack.new({ mapID = 1429, x = 0.48, y = 0.42 })
local API = c.FG.API
assert(API.VERSION >= 2, "needs ForeverGPS.API v2")

local function Key(m, ax, ay, bx, by) return ("%d:%.4f:%.4f:%.4f:%.4f"):format(m, ax, ay, bx, by) end
local out = { "-- Generated by tools/terrain_fixture.lua from Forever-GPS's real walking grid. Do not edit.",
              "return {", "  routes = {" }
local results = {}
local stats = {}
for _, r in ipairs(routes) do
    out[#out + 1] = ("    { mapID = %d, name = %q, points = { %s } },"):format(r.mapID, r.name, table.concat(r.points, ", "))
    local p, n = r.points, #r.points / 2
    local s = { name = r.name, legs = n, ms = 0, slowest = 0, counts = {} }
    for i = 1, n do
        local j = i % n + 1
        local ax, ay, bx, by = p[2 * i - 1], p[2 * i], p[2 * j - 1], p[2 * j]
        local t0 = os.clock()
        local res = API.LocalPath({ mapID = r.mapID, ax = ax, ay = ay, bx = bx, by = by })
        local dt = (os.clock() - t0) * 1000
        s.ms, s.slowest = s.ms + dt, math.max(s.slowest, dt)
        s.counts[res.status] = (s.counts[res.status] or 0) + 1
        results[Key(r.mapID, ax, ay, bx, by)] = res
    end
    stats[#stats + 1] = s
end
out[#out + 1] = "  },"
out[#out + 1] = "  results = {"
local keys = {}
for k in pairs(results) do keys[#keys + 1] = k end
table.sort(keys)
for _, k in ipairs(keys) do
    local res = results[k]
    local pts = {}
    for i = 1, #(res.points or {}) do pts[i] = ("%.5f"):format(res.points[i]) end
    out[#out + 1] = ("    [%q] = { status = %q, yards = %s, straight = %.1f, drops = %d%s },"):format(k, res.status,
        res.yards and ("%.1f"):format(res.yards) or "nil", res.straight or 0, res.drops or 0,
        #pts > 0 and (", points = { " .. table.concat(pts, ", ") .. " }") or "")
end
out[#out + 1] = "  },"
out[#out + 1] = "  timing = {"
for _, s in ipairs(stats) do
    local parts = {}
    for k, v in pairs(s.counts) do parts[#parts + 1] = k .. "=" .. v end
    table.sort(parts)
    out[#out + 1] = ("    { name = %q, legs = %d, totalMs = %.0f, slowestMs = %.0f, statuses = %q },"):format(s.name, s.legs,
        s.ms, s.slowest, table.concat(parts, " "))
    print(("%s: %d legs, %.0f ms total, slowest %.0f ms, %s"):format(s.name, s.legs, s.ms, s.slowest, table.concat(parts, " ")))
end
out[#out + 1] = "  },"
out[#out + 1] = "}"
local f = assert(io.open(outFile, "w"))
f:write(table.concat(out, "\n"), "\n")
f:close()
